const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('dist/data.js','utf8')+'\n'+fs.readFileSync('dist/app.js','utf8').split("document.addEventListener('click'")[0];
const context=vm.createContext({URLSearchParams,localStorage:{getItem:()=>null},document:{querySelector:()=>null},location:{hash:''}});
vm.runInContext(source,context);
const run=s=>vm.runInContext(s,context);
assert.equal(run('PRODUCTS.length'),36);
assert.equal(run('new Set(PRODUCTS.map(p=>p.id)).size'),36);
assert.equal(run('new Set(PRODUCTS.map(p=>p.category)).size'),7);
assert.equal(run('filteredProducts(new URLSearchParams("q=حقيبة")).length'),4);
assert.equal(run('filteredProducts(new URLSearchParams("category=shoes")).length'),8);
assert.equal(run('filteredProducts(new URLSearchParams("category=shoes&size=XL")).length'),0);
assert.equal(run('filteredProducts(new URLSearchParams("size=XL")).some(p=>p.unavailable.includes("XL"))'),false);
assert.equal(run('filteredProducts(new URLSearchParams("sort=low"))[0].price'),19);
run('cart=[{id:"p13",size:"40",qty:1}];coupon="LOOP10";delivery="standard"');
assert.equal(run('totals().discount'),4.8);assert.equal(run('totals().total'),46.2);
run('delivery="express"');assert.equal(run('totals().total'),50.2);
run('cart=[{id:"p13",size:"40",qty:2}];delivery="standard"');assert.equal(run('totals().shipping'),0);assert.equal(run('totals().total'),86.4);
run('cart=[]');assert.equal(run('totals().total'),0);
